-- One-time setup: warehouse, database, schemas, and the raw landing table.
-- Run as a role that can create warehouses and databases (e.g. SYSADMIN).

CREATE WAREHOUSE IF NOT EXISTS ART_WH
  WAREHOUSE_SIZE = 'XSMALL'
  AUTO_SUSPEND = 60
  AUTO_RESUME = TRUE;

CREATE DATABASE IF NOT EXISTS ART_HISTORY;
CREATE SCHEMA IF NOT EXISTS ART_HISTORY.RAW;
CREATE SCHEMA IF NOT EXISTS ART_HISTORY.ANALYTICS;  -- dbt builds here

CREATE OR REPLACE FILE FORMAT ART_HISTORY.RAW.CSV_FMT
  TYPE = 'CSV'
  SKIP_HEADER = 1
  FIELD_OPTIONALLY_ENCLOSED_BY = '"'
  NULL_IF = ('', 'NULL')
  EMPTY_FIELD_AS_NULL = TRUE;

CREATE STAGE IF NOT EXISTS ART_HISTORY.RAW.ARTWORKS_STAGE
  FILE_FORMAT = ART_HISTORY.RAW.CSV_FMT;

-- Raw table mirrors the CSV exactly. Everything stays as text here;
-- typing and cleanup happen in dbt staging so raw data is never altered.
CREATE TABLE IF NOT EXISTS ART_HISTORY.RAW.ARTWORKS (
  OBJECT_ID            VARCHAR,
  IS_PUBLIC_DOMAIN     VARCHAR,
  TITLE                VARCHAR,
  DEPARTMENT           VARCHAR,
  CLASSIFICATION       VARCHAR,
  OBJECT_NAME          VARCHAR,
  MEDIUM               VARCHAR,
  CULTURE              VARCHAR,
  PERIOD               VARCHAR,
  ARTIST_DISPLAY_NAME  VARCHAR,
  ARTIST_NATIONALITY   VARCHAR,
  ARTIST_BEGIN_DATE    VARCHAR,
  ARTIST_END_DATE      VARCHAR,
  OBJECT_DATE          VARCHAR,
  OBJECT_BEGIN_DATE    VARCHAR,
  OBJECT_END_DATE      VARCHAR,
  COUNTRY              VARCHAR,
  CREDIT_LINE          VARCHAR,
  METADATA_DATE        VARCHAR,
  _LOADED_AT           TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);
